def _norm(v):
    """Normalize a cell the same way the maps were keyed (xls ints arrive as floats)."""
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return str(v).strip()


def resolve_subyacente(tipo_valor, regla_cupon=None, moneda_emision=None, default=None):
    """Best-effort SUBYACENTE for an instrument not found in the live vector.

    Tries the precise (TIPO VALOR, REGLA CUPON, MONEDA EMISION) key first, then
    falls back to TIPO VALOR alone. Returns ``default`` if TIPO VALOR is unknown.
    """
    tv = _norm(tipo_valor)
    if regla_cupon is not None and moneda_emision is not None:
        hit = TV_REGLA_MONEDA_TO_SUBYACENTE.get((tv, _norm(regla_cupon), _norm(moneda_emision)))
        if hit is not None:
            return hit
    return TIPOVALOR_TO_SUBYACENTE.get(tv, default)

